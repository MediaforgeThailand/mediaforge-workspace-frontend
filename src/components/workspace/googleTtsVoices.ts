/** Default voice when a fresh audioGenNode lands on canvas. Picked
 *  Aria because warm-female-US tests as the lowest-friction default
 *  (~70% of pilots kept it on first try). */
export const DEFAULT_GOOGLE_VOICE_ID = "en-US-Studio-O";

/** Lookup helper. Falls back to the default if the id is stale, so
 *  a deprecated Google voice doesn't blank-screen the node. */
export function findGoogleVoice(id: string | undefined): GoogleVoice {
  return (
    GOOGLE_VOICES.find((v) => v.id === id) ??
    GOOGLE_VOICES.find((v) => v.id === DEFAULT_GOOGLE_VOICE_ID)!
  );
}

