/* ── Preview MP3 location ───────────────────────────────────────
 *
 * Pre-generated samples live in the `voice-previews` Supabase
 * Storage bucket on workspace dev (project id is wired through
 * VITE_SUPABASE_URL). The script in
 *   scripts/generate-voice-previews.ts
 * does a one-shot synth + upload. The bucket should be public-read
 * so the picker's <audio> tag can fetch the MP3s without an auth
 * token. Path layout:
 *     voice-previews/google/<voice-id>.mp3
 *
 * `voicePreviewUrl()` builds the absolute URL given a voice id. We
 * compute it client-side rather than persisting it on the GoogleVoice
 * record so a future bucket rename only needs one edit here.
 */
export function voicePreviewUrl(voiceId: string): string {
  const base =
    (typeof import.meta !== "undefined" &&
      (import.meta as unknown as { env?: { VITE_SUPABASE_URL?: string } }).env
        ?.VITE_SUPABASE_URL) ||
    "";
  if (!base) {
    // No Supabase URL configured — return an empty string and let the
    // dialog show "preview unavailable" rather than a broken request.
    return "";
  }
  // Public bucket → /storage/v1/object/public/<bucket>/<path>
  return `${base.replace(/\/$/, "")}/storage/v1/object/public/voice-previews/google/${encodeURIComponent(voiceId)}.mp3`;
}

