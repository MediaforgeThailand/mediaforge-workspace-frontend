/**
 * Google Cloud Text-to-Speech voice catalog.
 *
 * This is the catalog the audio gen picker shows by default. We curated
 * ~16 voices from Google's Studio / Neural2 / WaveNet families — the
 * tiers Freepik uses too — covering male/female × English (US/UK) and
 * Thai. Studio voices are highest quality (and ~10x more expensive),
 * Neural2 is the workhorse mid-tier, WaveNet is the budget option.
 *
 * Naming convention is Google's own: `<lang>-<region>-<family>-<id>`
 *   en-US-Studio-O   →  US English, Studio family, voice "O"
 *   en-US-Neural2-F  →  US English, Neural2 family, voice "F"
 *
 * Source for voice names + characteristics:
 *   https://cloud.google.com/text-to-speech/docs/voices
 *
 * Preview MP3 strategy:
 *   On first load the dialog renders the static `previewUrl` field
 *   below, which points at Supabase Storage at
 *     `voice-previews/google/<voice-id>.mp3`
 *   Pre-generated by `scripts/generate-voice-previews.ts` (run once
 *   per voice catalog change). The bucket is public-read so the
 *   browser can fetch them without an auth token. If the file 404s
 *   (e.g. before the script has been run on a fresh project) the
 *   dialog falls back to a silent "preview unavailable" state — no
 *   crash. See `previewBaseUrl` below for the storage location.
 */

export type GoogleVoiceLean = "male" | "female" | "neutral";

export type GoogleVoiceUseCase =
  | "advertisement"
  | "informative_educational"
  | "narrative_story"
  | "social_media";

export type GoogleVoiceLang = "en-US" | "en-GB" | "th-TH";

export type GoogleVoiceFamily = "Studio" | "Neural2" | "WaveNet" | "Standard";

export interface GoogleVoice {
  /** Exact Google API id — the `name` field in v1/voices. Passed
   *  verbatim to texttospeech.googleapis.com synthesize calls. */
  id: string;
  /** Friendly display name (e.g. "Aria — US English"). The id is
   *  ALSO shown as a subtitle so power users can verify which Google
   *  voice they're picking. */
  name: string;
  /** Short personality blurb shown under the row title. */
  characteristic: string;
  /** Perceptual lean — used by the gender filter chip. Google's API
   *  exposes ssmlGender (FEMALE/MALE/NEUTRAL); we store the same
   *  thing pre-mapped. */
  lean: GoogleVoiceLean;
  /** BCP-47 language code as Google expects it. Used for the flag
   *  chip in the UI and forwarded to the synth request. */
  languageCode: GoogleVoiceLang;
  /** Voice family — used to show a quality badge ("Studio" reads as
   *  premium in the picker so users know which voices use more
   *  credits). */
  family: GoogleVoiceFamily;
  /** Country flag emoji for the row chip (US / GB / TH). */
  flag: string;
  /** Mapped use cases — purely UX for the use-case filter cards. */
  useCases: GoogleVoiceUseCase[];
  /** Tint hint for the avatar fallback (initial-circle gradient). */
  tint: "violet" | "rose" | "amber" | "emerald" | "sky" | "zinc";
}

