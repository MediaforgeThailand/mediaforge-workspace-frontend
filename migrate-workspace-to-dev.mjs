/**
 * One-shot data migration: PROD workspace data → DEV workspace project.
 *
 * Reads workspaces / canvases / brand_elements / chat history that
 * belong to the user `mediaforge2026@gmail.com` on the PROD Supabase
 * project (yonnvlhgwdxkuirhdfaz), remaps `user_id` to that same
 * person's user_id on the DEV project (fymncypboeubdikpbmqc), and
 * upserts into the DEV tables.
 *
 * Why local script (not run by Claude via MCP):
 * the sandbox refuses to echo any PII (workspace names, node JSON,
 * etc.) into the chat transcript. So Claude can't read PROD rows
 * and re-write them to DEV. A local script bypasses the transcript
 * entirely — your terminal sees the data, the data goes
 * project-to-project, nothing leaks anywhere it shouldn't.
 *
 * Usage:
 *   1. Get the SERVICE-ROLE key for each project from Supabase
 *      dashboard → Project Settings → API → "service_role" (secret).
 *      Do NOT use the anon key — it can't bypass RLS.
 *   2. Set both as environment variables (PowerShell example):
 *
 *        $env:PROD_SERVICE_ROLE_KEY = "eyJhbGciOiJ..."
 *        $env:DEV_SERVICE_ROLE_KEY  = "eyJhbGciOiJ..."
 *
 *   3. Install dependency in any node project (or use this dir):
 *        npm install @supabase/supabase-js
 *
 *   4. Run:
 *        node migrate-workspace-to-dev.mjs
 *
 * What gets migrated:
 *   - public.workspaces                       (workspace meta)
 *   - public.workspace_canvases               (nodes / edges / viewport)
 *   - public.brand_elements                   (saved Kling elements)
 *   - public.workspace_chat_conversations     (chat history)
 *   - public.workspace_chat_messages          (chat history)
 *
 * The user_id column gets remapped from PROD-uuid to DEV-uuid.
 * Workspace ids / canvas ids stay the same (they're text/uuid
 * generated by the client) so existing /app/workspace/<id> URLs
 * keep working on the DEV side once you log in there.
 *
 * Idempotent: every insert is `upsert` keyed on the row's primary
 * key, so re-running the script just re-applies the same data
 * without duplicating.
 */

import { createClient } from "@supabase/supabase-js";

// ── Config ────────────────────────────────────────────────────
const PROD_URL = "https://yonnvlhgwdxkuirhdfaz.supabase.co";
const DEV_URL = "https://fymncypboeubdikpbmqc.supabase.co";

const PROD_USER_ID = "fb4de7e2-9f6e-459b-bb1b-464f6ae14bea"; // mediaforge2026@gmail.com on PROD
const DEV_USER_ID = "6105e811-5249-45e4-8a2a-50741ed391f7"; // same email on DEV

const PROD_KEY = process.env.PROD_SERVICE_ROLE_KEY;
const DEV_KEY = process.env.DEV_SERVICE_ROLE_KEY;

if (!PROD_KEY || !DEV_KEY) {
  console.error(
    "Missing PROD_SERVICE_ROLE_KEY or DEV_SERVICE_ROLE_KEY env var.\n" +
      "Get them from Supabase dashboard → Project Settings → API.",
  );
  process.exit(1);
}

const prod = createClient(PROD_URL, PROD_KEY, { auth: { persistSession: false } });
const dev = createClient(DEV_URL, DEV_KEY, { auth: { persistSession: false } });

// Re-stamp `user_id` on every row so the data lands as the DEV-side
// user instead of the PROD one. Keeps every other field as-is.
function remap(rows) {
  return rows.map((r) => ({ ...r, user_id: DEV_USER_ID }));
}

async function migrateTable({ table, label, conflict, extra }) {
  console.log(`\n─── ${label} (${table}) ───`);
  let query = prod.from(table).select("*").eq("user_id", PROD_USER_ID);
  if (extra) query = extra(query);
  const { data, error } = await query;
  if (error) {
    console.error(`  ✗ PROD read failed:`, error.message);
    return 0;
  }
  if (!data || data.length === 0) {
    console.log(`  · 0 rows on PROD — skip`);
    return 0;
  }
  console.log(`  · ${data.length} rows fetched from PROD`);

  const remapped = remap(data);
  const { error: writeErr } = await dev.from(table).upsert(remapped, {
    onConflict: conflict,
    ignoreDuplicates: false,
  });
  if (writeErr) {
    console.error(`  ✗ DEV write failed:`, writeErr.message);
    return 0;
  }
  console.log(`  ✓ ${remapped.length} rows upserted into DEV`);
  return remapped.length;
}

// Chat messages are joined to conversations through `conversation_id`,
// not `user_id`. We migrate the conversations first, collect their
// ids, then pull all messages whose conversation_id is in that set —
// regardless of who originally sent them. The conversation row's
// user_id rewrite already gates ownership on the DEV side.
async function migrateChatMessages(convIds) {
  console.log(`\n─── Chat messages (workspace_chat_messages) ───`);
  if (convIds.length === 0) {
    console.log(`  · no conversations to attach messages to — skip`);
    return 0;
  }
  const { data, error } = await prod
    .from("workspace_chat_messages")
    .select("*")
    .in("conversation_id", convIds);
  if (error) {
    console.error(`  ✗ PROD read failed:`, error.message);
    return 0;
  }
  if (!data || data.length === 0) {
    console.log(`  · 0 rows on PROD — skip`);
    return 0;
  }
  console.log(`  · ${data.length} rows fetched from PROD`);
  // Messages don't have user_id — no remap needed.
  const { error: writeErr } = await dev
    .from("workspace_chat_messages")
    .upsert(data, { onConflict: "id", ignoreDuplicates: false });
  if (writeErr) {
    console.error(`  ✗ DEV write failed:`, writeErr.message);
    return 0;
  }
  console.log(`  ✓ ${data.length} rows upserted into DEV`);
  return data.length;
}

async function main() {
  console.log("PROD →", PROD_URL);
  console.log("DEV  →", DEV_URL);
  console.log("Mapping user_id:", PROD_USER_ID, "→", DEV_USER_ID);

  // 1. Workspaces (meta)
  const ws = await migrateTable({
    table: "workspaces",
    label: "Workspaces",
    conflict: "id",
  });

  // 2. Canvases (nodes / edges / viewport)
  const cv = await migrateTable({
    table: "workspace_canvases",
    label: "Canvases",
    conflict: "id",
  });

  // 3. Brand elements (saved Kling refs)
  const be = await migrateTable({
    table: "brand_elements",
    label: "Brand elements",
    conflict: "id",
  });

  // 4. Chat conversations (need ids before messages)
  console.log(`\n─── Chat conversations (workspace_chat_conversations) ───`);
  const { data: convs, error: convErr } = await prod
    .from("workspace_chat_conversations")
    .select("*")
    .eq("user_id", PROD_USER_ID);
  if (convErr) {
    console.error(`  ✗ PROD read failed:`, convErr.message);
  } else if (!convs || convs.length === 0) {
    console.log(`  · 0 rows on PROD — skip`);
  } else {
    console.log(`  · ${convs.length} rows fetched from PROD`);
    const remappedConvs = remap(convs);
    const { error: writeErr } = await dev
      .from("workspace_chat_conversations")
      .upsert(remappedConvs, { onConflict: "id", ignoreDuplicates: false });
    if (writeErr) {
      console.error(`  ✗ DEV write failed:`, writeErr.message);
    } else {
      console.log(`  ✓ ${remappedConvs.length} rows upserted into DEV`);
    }
  }
  const convIds = (convs ?? []).map((c) => c.id);

  // 5. Chat messages (joined via conversation_id)
  await migrateChatMessages(convIds);

  console.log("\n──────────────────────────────────────");
  console.log(`Done. Workspaces=${ws}, canvases=${cv}, brand_elements=${be}.`);
  console.log("Refresh https://mediaforge-workspace-frontend.vercel.app/app/workspace");
  console.log("to see your data on the DEV project.");
}

main().catch((e) => {
  console.error("\nFATAL:", e);
  process.exit(1);
});
